const ids = ['paper-atelier-3d', 'neon-portal-3d', 'candy-world-3d', 'sculpture-index-3d', 'soft-garden-3d'];
describe('Intro homepage and shared 3D navigation', () => {
  it('shows actual directory counts, copy, shared menu and preserves legacy ranking filters', () => {
    cy.stubPublicApi();
    cy.intercept('GET', '**/api/v1/intro-homepage-config/', { template: 'sculpture-index-3d' });
    cy.visit('/');
    cy.wait('@getDirectory').its('request.query.limit').should('eq', '1');
    cy.get('.intro-counts dd').eq(0).should('contain.text', '2');
    cy.contains('h2', 'เกี่ยวกับเรา').should('be.visible');
    cy.contains('h2', 'นิยาม วีทูปเบอร์ไทย').should('exist');
    cy.get('.intro-paths').should('not.exist');
    cy.get('nav[aria-label="เมนูหลัก"] a').should('have.length', 5).then(links => expect([...links].map(a => a.textContent)).to.deep.equal(['หน้าแรก', 'จัดอันดับ', 'วีทูปเบอร์อิสระ', 'วีทูปเบอร์สังกัด', 'ค้นหา']));
    cy.viewport(390, 844);
    cy.document().its('documentElement.scrollWidth').should('be.lte', 390);
    cy.get('[aria-label="ธีมหน้าจอ"]').select('dark');
    cy.get('html').should('have.attr', 'data-theme', 'dark');
    cy.get('nav').contains('a', 'ค้นหา').click();
    cy.location('pathname').should('eq', '/discover');
    cy.contains('h1', 'ค้นหา VTuber ไทย').should('be.visible');
    cy.visit('/?period=monthly&category=views&month=2026-09&affiliation=indie&q=Aiko');
    cy.location('pathname').should('eq', '/home');
    cy.location('search').should('include', 'month=2026-09').and('include', 'q=Aiko');
  });
  it('previews, contains links, saves all five and publishes without altering discovery settings', () => {
    let published = 'sculpture-index-3d';
    cy.loginAs('manager'); cy.stubPublicApi();
    cy.intercept('GET', '**/api/v1/admin/settings/intro-homepage-template', req => req.reply({ intro_homepage_template: published }));
    cy.intercept('PUT', '**/api/v1/admin/settings/intro-homepage-template', req => { published = req.body.intro_homepage_template; expect(req.headers['x-csrf-token']).to.eq('test-csrf-token'); req.reply({ ok: true, intro_homepage_template: published }); }).as('saveIntro');
    cy.intercept('GET', '**/api/v1/intro-homepage-config/', req => req.reply({ template: published }));
    ids.forEach(id => {
      cy.visit('/admin/intro-homepage');
      cy.get('.intro-template-options button').eq(ids.indexOf(id)).click();
      cy.get('[data-testid="intro-homepage-preview"] .intro-page').should('have.attr', 'data-template', id);
      cy.get('[data-testid="intro-homepage-preview"]').contains('a', 'ค้นหา').click();
      cy.location('pathname').should('eq', '/admin/intro-homepage');
      cy.contains('button', 'บันทึกหน้าแรก').click();
      cy.wait('@saveIntro').its('request.body.intro_homepage_template').should('eq', id);
      cy.visit('/');
      cy.get('.intro-page').should('have.attr', 'data-template', id);
      cy.reload();
      cy.get('.intro-page').should('have.attr', 'data-template', id);
      cy.viewport(390, 844);
      cy.document().its('documentElement.scrollWidth').should('be.lte', 390);
      cy.viewport(768, 900);
      cy.document().its('documentElement.scrollWidth').should('be.lte', 768);
      cy.get('[aria-label="ธีมหน้าจอ"]').select('dark');
      cy.get('html').should('have.attr', 'data-theme', 'dark');
      cy.get('[aria-label="ธีมหน้าจอ"]').select('light');
      cy.viewport(1280, 900);
    });
    cy.visit('/admin/intro-homepage');
    cy.get('.intro-template-options button').eq(3).click();
    cy.contains('button', 'บันทึกหน้าแรก').click();
    cy.wait('@saveIntro');
    cy.screenshot('intro-template-admin', { capture: 'fullPage' });
    cy.visit('/');
    cy.get('.intro-page').should('have.attr', 'data-template', 'sculpture-index-3d');
    cy.visit('/discover');
    cy.get('.discovery-home').should('have.attr', 'data-template', 'search-first');
  });
});
